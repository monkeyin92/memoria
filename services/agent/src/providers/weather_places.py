class _CityBase(Enum):
    @property
    def standard_name(self) -> str:
        """The only place-derived string allowed on the wire."""

        name, _province = self.value
        return str(name)

    @property
    def province(self) -> str:
        _name, province = self.value
        return str(province)


def _city_enum() -> type[_CityBase]:
    # mypy reads Enum("Name", members) as a member lookup, so the builder is untyped.
    builder: Any = _CityBase
    created: type[_CityBase] = builder(
        "City",
        {name: (name, province) for name, province in _CITIES},
    )
    return created


City = _city_enum()


def _aliases() -> dict[str, _CityBase]:
    """Map every spoken form onto one city. A clash fails import."""

    found: dict[str, _CityBase] = {}

    def add(alias: str, city: _CityBase) -> None:
        current = found.get(alias)
        if current is not None and current is not city:
            raise ValueError(f"weather alias maps to two cities: {alias}")
        found[alias] = city

    for city in City:
        add(city.standard_name, city)
        if not city.standard_name.endswith("市"):
            add(f"{city.standard_name}市", city)
    for alias, parent in _DISTRICTS:
        add(alias, City[parent])
    return found


_ALIASES: Mapping[str, _CityBase] = _aliases()
_ALIAS_KEYS = tuple(sorted(_ALIASES, key=len, reverse=True))
_STRIP = re.compile(r"[\s，,。！？!?；;：:、]")
_STOPWORDS = (
    "帮我查一下",
    "想知道",
    "告诉我",
    "查一下",
    "查一查",
    "问一下",
    "今天",
    "明天",
    "后天",
    "现在",
    "当前",
    "外面",
    "当地",
    "最近",
    "请问",
    "问问",
    "帮我",
    "查询",
    "查查",
    "看看",
    "的",
)
# These characters continue a different place (南京路, 吉林省) rather than
# starting the rest of the sentence (上海哪里). 区 is handled separately so
# 海淀区 still matches and 朝阳区 does not.
_BLOCKED_SUFFIX = frozenset("路街巷道桥省")


def _suffix_blocks(alias: str, nxt: str) -> bool:
    if nxt in _BLOCKED_SUFFIX:
        return True
    return nxt == "区" and f"{alias}区" not in _ALIASES


def _cleaned_prefix(text: str) -> str:
    compact = _STRIP.sub("", text or "")
    before, _separator, _after = compact.partition("天气")
    for stopword in _STOPWORDS:
        before = before.replace(stopword, "")
    return before


def find_city(text: str) -> _CityBase | None:
    """The one allowlisted city named before 天气, or None.

    Spans are exact alias hits in the cleaned prefix. Zero hits, or two
    different cities, return None. A city that appears only after 天气 is
    not a span.
    """

    clean = _cleaned_prefix(text)
    found: set[_CityBase] = set()
    index = 0
    while index < len(clean):
        matched: _CityBase | None = None
        matched_end = index
        for alias in _ALIAS_KEYS:
            if not clean.startswith(alias, index):
                continue
            end = index + len(alias)
            if end != len(clean) and _suffix_blocks(alias, clean[end]):
                continue
            matched = _ALIASES[alias]
            matched_end = end
            break
        if matched is None:
            index += 1
            continue
        found.add(matched)
        index = matched_end
    if len(found) != 1:
        return None
    return next(iter(found))


