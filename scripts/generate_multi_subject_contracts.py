        lines.append(f"class {name}(BaseModel):")
        lines.append(f'    """{_one_line(schema["description"])}"""')
        lines.append('    model_config = ConfigDict(extra="forbid", frozen=True)')
        lines.append("")
        fields = _object_fields(name, schema, object_defs, canonical)
        for field in fields:
            lines.append("    " + _python_field_line(field))
        for field in fields:
            if not field.has_const:
                continue
            lines.append("")
            lines.append(f"    @field_validator({json.dumps(field.name)}, mode=\"before\")")
            lines.append("    @classmethod")
            lines.append(f"    def _{field.name}_const(cls, value: object) -> object:")
            lines.append(f"        if value != {json.dumps(field.const_value, ensure_ascii=False)}:")
            lines.append(f'            raise ValueError("{field.name}: const mismatch")')
            lines.append("        return value")
        for field in fields:
            if field.format != "date-time":
                continue
            lines.append("")
            lines.append(f"    @field_validator({json.dumps(field.name)}, mode=\"before\")")
            lines.append("    @classmethod")
            lines.append(f"    def _{field.name}_rfc3339(cls, value: object) -> object:")
            lines.append("        if value is None:")
            lines.append("            return None")
            lines.append("        if not isinstance(value, str) or not RFC3339_STRICT_PATTERN.fullmatch(value):")
            lines.append(f'            raise ValueError("{field.name}: must be RFC3339 string with T separator and offset/Z")')
            lines.append('        return value.replace("t", "T").replace("z", "Z")')
