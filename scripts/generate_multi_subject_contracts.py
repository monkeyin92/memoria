def _go_pattern_helpers(object_defs: dict[str, Any]) -> dict[str, str]:
    """Map each unique pattern to its deterministic helper name (schema order)."""
    patterns: dict[str, str] = {}
    for schema in object_defs.values():
        for pschema in schema.get("properties", {}).values():
            _collect_patterns(pschema, patterns)
    return patterns


def _collect_patterns(schema: dict[str, Any], patterns: dict[str, str]) -> None:
    if not isinstance(schema, dict):
        return
    if "anyOf" in schema:
        for branch in schema["anyOf"]:
            _collect_patterns(branch, patterns)
        return
    pattern = schema.get("pattern")
    if isinstance(pattern, str) and pattern not in patterns:
        patterns[pattern] = f"contractPattern{len(patterns)}"
    items = schema.get("items")
    if isinstance(items, dict):
        _collect_patterns(items, patterns)


