def _firmware_field_spec(field: FieldSpec) -> dict[str, Any]:
    entry: dict[str, Any] = {
        "name": field.name,
        "json_type": field.json_type,
        "nullable": field.nullable,
        "required": field.required,
    }
    if field.ref_kind:
        entry["ref"] = f"{CANONICAL_REF_PREFIX}{field.ref_name}" if field.ref_kind == "canonical" else f"{OBJECT_REF_PREFIX}{field.ref_name}"
    if field.enum_values:
        entry["enum"] = list(field.enum_values)
    if field.has_const:
        entry["const"] = field.const_value
    for key, value in (
        ("min_length", field.min_length),
        ("max_length", field.max_length),
        ("pattern", field.pattern),
        ("format", field.format),
        ("minimum", field.minimum),
        ("maximum", field.maximum),
        ("min_items", field.min_items),
        ("max_items", field.max_items),
        ("max_properties", field.max_properties),
        ("unique_items", field.unique_items or None),
    ):
        if value is not None:
            entry[key] = value
    if field.json_type == "array":
        entry["items"] = _firmware_schema_spec(
            cast(dict[str, Any], field.value_schema["items"])
        )
        if field.item_ref_kind:
            entry["items_ref"] = (
                f"{CANONICAL_REF_PREFIX}{field.item_ref_name}"
                if field.item_ref_kind == "canonical"
                else f"{OBJECT_REF_PREFIX}{field.item_ref_name}"
            )
        else:
            entry["items_type"] = field.item_json_type
    if field.additional_properties:
        entry["additional_properties"] = field.additional_properties
    return entry


def _firmware_schema_spec(schema: dict[str, Any]) -> dict[str, Any]:
    """Compact recursive schema subset consumed by constrained firmware."""

    if "$ref" in schema:
        return {"ref": schema["$ref"]}
    entry: dict[str, Any] = {"json_type": schema.get("type")}
    for source, target in (
        ("const", "const"),
        ("minLength", "min_length"),
        ("maxLength", "max_length"),
        ("pattern", "pattern"),
        ("format", "format"),
        ("minimum", "minimum"),
        ("maximum", "maximum"),
        ("minItems", "min_items"),
        ("maxItems", "max_items"),
        ("maxProperties", "max_properties"),
        ("uniqueItems", "unique_items"),
    ):
        if source in schema:
            entry[target] = schema[source]
    if "items" in schema:
        entry["items"] = _firmware_schema_spec(cast(dict[str, Any], schema["items"]))
    additional = schema.get("additionalProperties")
    if isinstance(additional, dict):
        entry["additional_properties"] = _firmware_schema_spec(additional)
    elif additional is True:
        entry["additional_properties"] = True
    return entry


def _generate_commonjs(
    defs: dict[str, dict[str, Any]],
    object_defs: dict[str, dict[str, Any]],
    contract_lifecycle: tuple[dict[str, Any], ...],
    schema_version: int,
    objects_version: int,
    schema_hash: str,
) -> str:
    """Generate a dependency-free CommonJS artifact for WeChat and Node consumers."""
    lines = [
        "/*",
        *[f" * {header_line}" for header_line in HEADER.splitlines()],
        f" * Source hash: sha256:{schema_hash}",
        " *",
        " * Dependency-free CommonJS for the WeChat JavaScript runtime and Node tests.",
        " */",
        '"use strict";',
        "",
        f"const CONTRACTS_SCHEMA_VERSION = {schema_version};",
        f"const OBJECT_CONTRACTS_VERSION = {objects_version};",
        f"const SOURCE_HASH = {json.dumps(schema_hash)};",
        f"const SOURCE_SCHEMA = {json.dumps(SCHEMA_ID)};",
        "",
        "const CONTRACT_LIFECYCLE = Object.freeze({",
    ]
    for entry in contract_lifecycle:
        lifecycle = {
            "lifecycle": entry["lifecycle"],
            "consumer_mode": entry["consumer_mode"],
            "new_producer": entry["new_producer"],
            "replacement": entry["replacement"],
        }
        lines.append(
            f"  {json.dumps(entry['name'])}: Object.freeze("
            f"{json.dumps(lifecycle, ensure_ascii=False, separators=(',', ':'))}),"
        )
    lines.extend(
        [
            "});",
            "",
            "const CANONICAL_PRODUCER_CONTRACTS = Object.freeze([",
        ]
    )
    for entry in contract_lifecycle:
        if entry["new_producer"] == "allowed":
            lines.append(f"  {json.dumps(entry['name'])},")
    lines.extend(
        [
            "]);",
            "",
            "const MIGRATION_ONLY_CONTRACTS = Object.freeze([",
        ]
    )
    for entry in contract_lifecycle:
        if entry["consumer_mode"] == "migration_only":
            lines.append(f"  {json.dumps(entry['name'])},")
    lines.extend(
        [
            "]);",
            "",
            "function isNewProducerContract(name) {",
            "  const lifecycle = CONTRACT_LIFECYCLE[name];",
            '  return Boolean(lifecycle && lifecycle.new_producer === "allowed");',
            "}",
            "",
            "function requireNewProducerContract(name) {",
            "  if (isNewProducerContract(name)) return;",
            "  const lifecycle = CONTRACT_LIFECYCLE[name];",
            "  const replacement = lifecycle ? lifecycle.replacement : null;",
            '  throw new Error(`${name}: forbidden for new producers; replacement=${replacement}`);',
            "}",
            "",
        ]
    )

    for name, schema in defs.items():
        values = cast(list[str], schema["enum"])
        meta = _meta_of(schema)
        screaming = _screaming(name)
        keys = [_commonjs_key(name, value) for value in values]
        if len(set(keys)) != len(keys):
            _fail(f"{name}: duplicate CommonJS property keys {keys!r}")
        lines.append(f"const {name} = Object.freeze({{")
        for key, value in zip(keys, values, strict=True):
            lines.append(f"  {json.dumps(key)}: {json.dumps(value, ensure_ascii=False)},")
        lines.extend(
            [
                "});",
                f"const {screaming}_VALUES = Object.freeze("
                f"{json.dumps(values, ensure_ascii=False, separators=(',', ':'))});",
                f"const {screaming}_DEFAULT = "
                f"{json.dumps(meta.get('default'), ensure_ascii=False)};",
                f"function is{name}(value) {{",
                f'  return typeof value === "string" && {screaming}_VALUES.includes(value);',
                "}",
                "",
            ]
        )

    lines.append("const ENUM_REGISTRY = Object.freeze({")
    for name, schema in defs.items():
        meta = _meta_of(schema)
        screaming = _screaming(name)
        lines.extend(
            [
                f"  {json.dumps(name)}: Object.freeze({{",
                f"    values: {screaming}_VALUES,",
                f"    default: {screaming}_DEFAULT,",
                f"    contract_version: {meta['contract_version']},",
                f"    missing_value_policy: {json.dumps(meta['missing_value_policy'])},",
                f"    guard: is{name},",
                "  }),",
            ]
        )
    lines.extend(["});", ""])

    context_hash_inputs = {
        name: schema["x-memoria-context-hash-inputs"]
        for name, schema in object_defs.items()
        if "x-memoria-context-hash-inputs" in schema
    }
    lines.append("const CONTEXT_HASH_INPUTS = Object.freeze({")
    for name, paths in context_hash_inputs.items():
        lines.append(
            f"  {json.dumps(name)}: Object.freeze("
            f"{json.dumps(paths, ensure_ascii=False, separators=(',', ':'))}),"
        )
    lines.extend(["});", "", "module.exports = {"])
    lines.extend(
        [
            "  CONTRACTS_SCHEMA_VERSION,",
            "  OBJECT_CONTRACTS_VERSION,",
            "  SOURCE_HASH,",
            "  SOURCE_SCHEMA,",
            "  CONTRACT_LIFECYCLE,",
            "  CANONICAL_PRODUCER_CONTRACTS,",
            "  MIGRATION_ONLY_CONTRACTS,",
            "  CONTEXT_HASH_INPUTS,",
            "  ENUM_REGISTRY,",
            "  isNewProducerContract,",
            "  requireNewProducerContract,",
        ]
    )
    for name in defs:
        screaming = _screaming(name)
        lines.extend(
            [
                f"  {name},",
                f"  {screaming}_VALUES,",
                f"  {screaming}_DEFAULT,",
                f"  is{name},",
            ]
        )
    lines.extend(["};", ""])
    return "\n".join(lines)


def _generate_firmware(
    defs: dict[str, dict[str, Any]],
    object_defs: dict[str, dict[str, Any]],
    contract_lifecycle: tuple[dict[str, Any], ...],
    schema_version: int,
    objects_version: int,
    schema_hash: str,
) -> str:
    payload: dict[str, Any] = {
        "schema": SCHEMA_ID,
        "schema_version": schema_version,
        "objects_version": objects_version,
        "source_hash": schema_hash,
        "generated_by": "scripts/generate_multi_subject_contracts.py",
        "contract_lifecycle": list(contract_lifecycle),
        "canonical_producer_contracts": [
            entry["name"]
            for entry in contract_lifecycle
            if entry["new_producer"] == "allowed"
        ],
        "migration_only_contracts": [
            entry["name"]
            for entry in contract_lifecycle
            if entry["consumer_mode"] == "migration_only"
        ],
        "enums": [],
        "objects": [],
    }
    for name, schema in defs.items():
        meta = _meta_of(schema)
        entry: dict[str, Any] = {
            "name": name,
            "missing_value_policy": meta["missing_value_policy"],
        }
        if "default" in meta:
            entry["default"] = meta["default"]
        entry["values"] = list(schema["enum"])
        payload["enums"].append(entry)
    canonical: set[str] = set(defs)
    for name, schema in object_defs.items():
        kind = _definition_kind(schema)
        if kind == "enum":
            payload["objects"].append({"name": name, "kind": "enum", "values": list(schema["enum"])})
            continue
        object_entry: dict[str, Any] = {"name": name, "kind": "object"}
        if kind == "extend":
            object_entry["extends"] = f"{OBJECT_REF_PREFIX}{schema['x-memoria-extends']}"
        object_entry["required"] = list(schema.get("required", []))
        object_entry["properties"] = [
            _firmware_field_spec(field)
            for field in _object_fields(name, schema, object_defs, canonical)
        ]
        invariants = _normalized_invariants(schema)
        if invariants:
            object_entry["invariants"] = invariants
        if "x-memoria-context-hash-inputs" in schema:
            object_entry["context_hash_inputs"] = list(
                schema["x-memoria-context-hash-inputs"]
            )
        payload["objects"].append(object_entry)
    return json.dumps(payload, ensure_ascii=False, indent=2) + "\n"


OUTPUT_FILES: dict[str, str] = {
    "packages/contracts/generated/python/multi_subject_contracts.py": "python",
    "packages/contracts/generated/typescript/multi_subject_contracts.ts": "typescript",
    "packages/contracts/generated/go/multi_subject_contracts.go": "go",
    "packages/contracts/generated/firmware/multi_subject_contracts.compact.json": "firmware",
    "apps/miniprogram/generated/multi-subject-contracts.js": "commonjs",
}


def build_outputs(root: Path) -> dict[Path, str]:
    schema_path = root / SCHEMA_REL_PATH
    if not schema_path.is_file():
        raise FileNotFoundError(f"canonical schema not found: {schema_path}")
    data = load_schema(schema_path)
    schema_hash = hashlib.sha256(schema_path.read_bytes()).hexdigest()
    defs: dict[str, dict[str, Any]] = data["$defs"]
    object_defs: dict[str, dict[str, Any]] = _validate_objects(data)
    schema_version: int = data["properties"]["schema_version"]["const"]
    objects_version: int = data["objects"]["properties"]["objects_version"]["const"]
    contract_lifecycle = _contract_lifecycle(data)
    generators = {
        "python": _generate_python,
        "typescript": _generate_typescript,
        "go": _generate_go,
        "firmware": _generate_firmware,
        "commonjs": _generate_commonjs,
    }
    outputs: dict[Path, str] = {}
    for rel, language in OUTPUT_FILES.items():
        outputs[root / rel] = (
            generators[language](
                defs,
                object_defs,
                contract_lifecycle,
                schema_version,
                objects_version,
                schema_hash,
            ).rstrip("\n")
            + "\n"
        )
    return outputs


def run(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate Memoria multi-subject canonical contract artifacts.")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="write generated artifacts (default)")
    mode.add_argument("--check", action="store_true", help="verify on-disk artifacts match fresh generation; exit 1 on drift")
    parser.add_argument("--output-root", type=Path, default=None, help="repository root (default: two levels above this script)")
    args = parser.parse_args(argv)
    root = (args.output_root or Path(__file__).resolve().parent.parent).resolve()
    outputs = build_outputs(root)
    if args.check:
        drifted: list[Path] = []
        for path, content in outputs.items():
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                drifted.append(path)
        if drifted:
            for path in drifted:
                print(f"DRIFT: {path.relative_to(root)}")
            print(f"multi-subject contracts: {len(drifted)} artifact(s) out of date; run the generator with --write")
            return 1
        print(f"multi-subject contracts: {len(outputs)} artifact(s) in sync (no diff)")
        return 0
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"WROTE: {path.relative_to(root)}")
    print(f"multi-subject contracts: generated {len(outputs)} artifact(s)")
    return 0


if __name__ == "__main__":
    sys.exit(run())
