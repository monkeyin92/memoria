    lines.append(f"export interface {name} {{")
    for field in fields:
        optional = "?" if not field.required else ""
        lines.append(f"  {field.name}{optional}: {_ts_type(field)};")
    lines.append("}")
    lines.append("")
    lines.append(f"export function is{name}(value: unknown): value is {name} {{")
    lines.append(f"  return validate{name}(value).length === 0;")
    lines.append("}")
    lines.append("")
    lines.append(f"export function validate{name}(value: unknown): string[] {{")
    lines.append("  const errors: string[] = [];")
    lines.append(f"  if (typeof value !== \"object\" || value === null) return [\"{name}: expected an object\"];")
    lines.append("  const v = value as Record<string, unknown>;")
    allowed = "[" + ", ".join(json.dumps(f.name) for f in fields) + "]"
    lines.append(f"  const allowed = new Set({allowed});")
    lines.append("  for (const key of Object.keys(v)) {")
    lines.append(f"    if (!allowed.has(key)) errors.push(`{name}.${{key}}: unknown property`);")
    lines.append("  }")
    for field in fields:
        if field.required:
            lines.append(f"  if (!(\"{field.name}\" in v)) errors.push(\"{name}.{field.name}: missing required property\");")
            lines.append(f"  else if (!({_ts_check(field)})) errors.push(\"{name}.{field.name}: invalid value\");")
        else:
            lines.append(f"  if (\"{field.name}\" in v && !({_ts_check(field)})) errors.push(\"{name}.{field.name}: invalid value\");")
    if _normalized_invariants(schema):
        lines.append(f"  errors.push(...validateContractInvariants({name!r}, v, OBJECT_INVARIANTS.{name}));")
    lines.append("  return errors;")
    lines.append("}")
    lines.append("")
    return lines


