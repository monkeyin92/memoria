@dataclass(frozen=True)
class FieldSpec:
    name: str
    json_type: str  # string | integer | number | boolean | array | object | enum | ref
    ref_kind: str | None  # canonical | object
    ref_name: str | None
    enum_values: tuple[str, ...] | None
    has_const: bool
    const_value: str | int | bool | None
    nullable: bool
    required: bool
    min_length: int | None
    max_length: int | None
    pattern: str | None
    format: str | None
    minimum: float | None
    maximum: float | None
    min_items: int | None
    max_items: int | None
    max_properties: int | None
    item_ref_kind: str | None
    item_ref_name: str | None
    item_json_type: str | None
    item_min_length: int | None
    item_max_length: int | None
    additional_properties: str | None
    unique_items: bool
    value_schema: dict[str, Any]


def _field_spec(
    name: str,
    schema: dict[str, Any],
    *,
    required: bool,
    object_defs: dict[str, Any],
    canonical: set[str],
) -> FieldSpec:
    base = dict(schema)
    nullable = False
    if "anyOf" in base:
        branches = base["anyOf"]
        non_null = [b for b in branches if b.get("type") != "null"]
        if len(non_null) != 1 or len(branches) != 2:
            _fail(f"objects.{name}: anyOf must be value + null")
        base = dict(non_null[0])
        nullable = True
    if isinstance(base.get("type"), list):
        types = base["type"]
        if types.count("null") != 1 or len(types) != 2:
            _fail(f"objects.{name}: type list must be [<type>, \"null\"]")
        nullable = True
        base = dict(base)
        base["type"] = types[0] if types[0] != "null" else types[1]
    ref_kind = ref_name = None
    enum_values: tuple[str, ...] | None = None
    json_type: str
    if "$ref" in base:
        ref_kind, ref_name = _resolve_ref(base["$ref"], object_defs, canonical)
        json_type = "ref"
    elif "enum" in base:
        enum_values = tuple(base["enum"])
        json_type = "enum"
    else:
        raw_json_type = base.get("type")
        if not isinstance(raw_json_type, str):
            _fail(f"objects.{name}: missing type")
        json_type = raw_json_type

    item_kind = item_name = item_primitive = None
    items = base.get("items", {}) if json_type == "array" else {}
    if isinstance(items, dict) and "$ref" in items:
        item_kind, item_name = _resolve_ref(items["$ref"], object_defs, canonical)
    elif isinstance(items, dict) and "enum" in items:
        item_kind = "enum"
    elif isinstance(items, dict):
        item_primitive = items.get("type")

    addl = base.get("additionalProperties") if json_type == "object" else None
    addl_kind = "string" if isinstance(addl, dict) and addl.get("type") == "string" else None
    return FieldSpec(
        name=name,
        json_type=json_type,
        ref_kind=ref_kind,
        ref_name=ref_name,
        enum_values=enum_values,
        has_const="const" in base,
        const_value=base.get("const"),
        nullable=nullable,
        required=required,
        min_length=base.get("minLength"),
        max_length=base.get("maxLength"),
        pattern=base.get("pattern"),
        format=base.get("format"),
        minimum=base.get("minimum"),
        maximum=base.get("maximum"),
        min_items=base.get("minItems"),
        max_items=base.get("maxItems"),
        max_properties=base.get("maxProperties"),
        item_ref_kind=item_kind,
        item_ref_name=item_name,
        item_json_type=item_primitive if isinstance(item_primitive, str) else None,
        item_min_length=items.get("minLength") if isinstance(items, dict) else None,
        item_max_length=items.get("maxLength") if isinstance(items, dict) else None,
        additional_properties=addl_kind,
        unique_items=bool(base.get("uniqueItems")),
        value_schema=base,
    )


def _object_fields(name: str, schema: dict[str, Any], object_defs: dict[str, Any], canonical: set[str]) -> list[FieldSpec]:
    required = set(schema.get("required", []))
    properties = schema.get("properties")
    if not isinstance(properties, dict):
        _fail(f"objects.{name}: missing properties")
    return [
        _field_spec(pname, pschema, required=pname in required, object_defs=object_defs, canonical=canonical)
        for pname, pschema in properties.items()
    ]


