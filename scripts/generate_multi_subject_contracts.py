def _validate_objects(data: dict[str, Any]) -> dict[str, dict[str, Any]]:
    objects = data.get("objects")
    if not isinstance(objects, dict):
        _fail("missing objects section")
    props = objects.get("properties")
    if not isinstance(props, dict):
        _fail("objects.properties missing")
    version = props.get("objects_version", {}).get("const")
    if not isinstance(version, int) or version < 1:
        _fail("objects_version must be a positive integer const")
    defs_section = props.get("definitions")
    if not isinstance(defs_section, dict):
        _fail("objects.definitions must be an object")
    defs = defs_section.get("properties")
    if not isinstance(defs, dict) or not defs:
        _fail("objects.definitions must be a non-empty object")
    contracts = props.get("contracts", {}).get("const")
    if not isinstance(contracts, list) or any(not isinstance(entry, dict) for entry in contracts):
        _fail("objects.contracts must be a lifecycle record list")
    contract_names = tuple(entry.get("name") for entry in contracts)
    if contract_names != REQUIRED_OBJECT_CONTRACTS:
        _fail(f"objects.contracts drift: {contract_names!r} != {REQUIRED_OBJECT_CONTRACTS}")
    lifecycle_keys = {"name", "lifecycle", "consumer_mode", "new_producer", "replacement"}
    forbidden: dict[str, str] = {}
    for entry in contracts:
        if set(entry) != lifecycle_keys:
            _fail(f"objects.contracts.{entry.get('name')}: lifecycle keys drift")
        name = entry["name"]
        if entry["lifecycle"] == "current":
            if entry != {
                "name": name,
                "lifecycle": "current",
                "consumer_mode": "canonical",
                "new_producer": "allowed",
                "replacement": None,
            }:
                _fail(f"objects.contracts.{name}: current contract lifecycle invalid")
        elif entry["lifecycle"] == "deprecated":
            replacement = entry.get("replacement")
            if (
                entry.get("consumer_mode") != "migration_only"
                or entry.get("new_producer") != "forbidden"
                or not isinstance(replacement, str)
                or replacement not in REQUIRED_OBJECT_CONTRACTS
            ):
                _fail(f"objects.contracts.{name}: deprecated contract lifecycle invalid")
            forbidden[name] = replacement
        else:
            _fail(f"objects.contracts.{name}: unknown lifecycle")
    if forbidden != DEPRECATED_CONTRACT_REPLACEMENTS:
        _fail(
            "objects.contracts deprecated producer set drift: "
            f"{forbidden!r} != {DEPRECATED_CONTRACT_REPLACEMENTS!r}"
        )
    canonical = set(data.get("$defs", {}))
    for name in REQUIRED_OBJECT_CONTRACTS:
        if name not in defs:
            _fail(f"objects.contracts references missing definition {name}")
    for name, schema in defs.items():
        _validate_object_def(name, schema, defs, canonical)
    for name, schema in defs.items():
        base_name = schema.get("x-memoria-extends")
        if not isinstance(base_name, str):
            continue
        base = defs[base_name]
        base_props = set(base.get("properties", {}))
        own_props = set(schema.get("properties", {}))
        if not base_props <= own_props:
            _fail(f"objects.{name}: must be a strict superset of {base_name} fields")
        base_required = set(base.get("required", []))
        own_required = set(schema.get("required", []))
        if not base_required <= own_required:
            _fail(f"objects.{name}: required must cover {base_name} required fields")
    return defs


