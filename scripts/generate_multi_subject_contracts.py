    lines.append("")
    enum_registry = ", ".join(f'"{name}": {name}' for name in object_enum_names)
    lines.append(f"OBJECT_ENUM_REGISTRY: dict[str, type[enum.Enum]] = {{{enum_registry}}}")
    lines.append("")
    canonical: set[str] = set(defs)
    for name, schema in object_defs.items():
        kind = _definition_kind(schema)
        if kind == "enum":
            continue
