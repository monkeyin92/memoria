def _stable_contract_key(value: object) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))

def _rule_matches(payload: dict[str, object], when: Any) -> bool:
    if not isinstance(when, dict):
        return True
    value = _path_get(payload, str(when["path"]))
    if "equals" in when:
        return bool(value == when["equals"])
    if "not_equals" in when:
        return bool(value != when["not_equals"])
    if "in" in when:
        return value in when["in"]
    if "not_in" in when:
        return value not in when["not_in"]
    return False

def _contract_datetime(value: object, path: str) -> datetime:
    if not isinstance(value, str):
        raise ValueError(f"{path}: expected RFC3339 string")
    return datetime.fromisoformat(value.replace("Z", "+00:00").replace("z", "+00:00"))

def _validate_contract_invariants(name: str, payload: dict[str, object], rules: tuple[dict[str, Any], ...]) -> None:
    for rule in rules:
        kind = rule["kind"]
        when = rule.get("when")
        if not _rule_matches(payload, when):
            continue
        if kind == "paired_arrays":
            left = _path_get(payload, str(rule["left_path"]))
            right = _path_get(payload, str(rule["right_path"]))
            if not isinstance(left, list) or not isinstance(right, list) or len(left) != len(right):
                raise ValueError(f"{name}: paired arrays must have equal length")
        elif kind == "value_pairs":
            left = _path_get(payload, str(rule["left_field"]))
            right = _path_get(payload, str(rule["right_field"]))
            pairs = rule["pairs"]
            if not isinstance(pairs, dict):
                raise ValueError(f"{name}: invalid value-pair rule")
            if left in pairs and right != pairs[left]:
                raise ValueError(f"{name}: restricted authority pair mismatch")
            if rule.get("bidirectional") and right in pairs.values():
                inverse = {value: key for key, value in pairs.items()}
                if left != inverse[right]:
                    raise ValueError(f"{name}: restricted authority pair mismatch")
        elif kind == "conditional":
            for path in rule.get("require_non_null", []):
                if _path_get(payload, str(path)) in (None, _PATH_MISSING):
                    raise ValueError(f"{name}.{path}: condition requires non-null")
            for path in rule.get("require_null", []):
                if _path_get(payload, str(path)) is not None:
                    raise ValueError(f"{name}.{path}: condition requires null")
            for path in rule.get("require_non_empty", []):
                value = _path_get(payload, str(path))
                if value in (None, _PATH_MISSING, "", [], {}):
                    raise ValueError(f"{name}.{path}: condition requires non-empty")
            for path in rule.get("require_empty", []):
                if _path_get(payload, str(path)) not in ([], {}, ""):
                    raise ValueError(f"{name}.{path}: condition requires empty")
            equals = rule.get("require_equals", {})
            if isinstance(equals, dict):
                for path, expected in equals.items():
                    if _path_get(payload, path) != expected:
                        raise ValueError(f"{name}.{path}: condition requires exact value")
            allowed = rule.get("require_in", {})
            if isinstance(allowed, dict):
                for path, values in allowed.items():
                    if _path_get(payload, path) not in values:
                        raise ValueError(f"{name}.{path}: condition rejects value")
            forbidden = rule.get("forbid_contains", {})
            if isinstance(forbidden, dict):
                for path, values in forbidden.items():
                    actual = _path_get(payload, path)
                    if isinstance(actual, list) and any(value in actual for value in values):
                        raise ValueError(f"{name}.{path}: condition forbids capability")
        elif kind in ("equal", "distinct"):
            paths = rule["paths"]
            values = [_path_get(payload, str(path)) for path in paths]
            keys = [_stable_contract_key(value) for value in values]
            if kind == "equal" and len(set(keys)) != 1:
                raise ValueError(f"{name}: exact fence paths differ")
            if kind == "distinct" and len(set(keys)) != len(keys):
                raise ValueError(f"{name}: authority values must be distinct")
        elif kind == "set_equal":
            paths = rule["paths"]
            values = [_path_get(payload, str(path)) for path in paths]
            if any(not isinstance(value, list) for value in values):
                raise ValueError(f"{name}: set-equality paths must be arrays")
            sets = [{_stable_contract_key(item) for item in value} for value in values if isinstance(value, list)]
            if not sets or any(value != sets[0] for value in sets[1:]):
                raise ValueError(f"{name}: exact subject/evidence set differs")
        elif kind == "record_set_equal":
            left = _path_get(payload, str(rule["left_path"]))
            right = _path_get(payload, str(rule["right_path"]))
            if not isinstance(left, list) or not isinstance(right, list):
                raise ValueError(f"{name}: record-set paths must be arrays")
            left_fields = rule["left_fields"]
            right_fields = rule["right_fields"]
            left_keys = {_stable_contract_key([item[field] for field in left_fields]) for item in left if isinstance(item, dict)}
            right_keys = {_stable_contract_key([item[field] for field in right_fields]) for item in right if isinstance(item, dict)}
            if len(left_keys) != len(left) or len(right_keys) != len(right) or left_keys != right_keys:
                raise ValueError(f"{name}: approval snapshot revisions/hashes differ")
        elif kind == "record_coverage":
            required = _path_get(payload, str(rule["required_ids_path"]))
            records = _path_get(payload, str(rule["records_path"]))
            if not isinstance(required, list) or not isinstance(records, list):
                raise ValueError(f"{name}: record coverage requires arrays")
            ids = [item[rule["record_id_field"]] for item in records if isinstance(item, dict)]
            if len(ids) != len(records) or len(ids) != len(set(ids)) or set(ids) != set(required):
                raise ValueError(f"{name}: record coverage is incomplete")
        elif kind == "time_order":
            earlier = _contract_datetime(_path_get(payload, str(rule["earlier_path"])), str(rule["earlier_path"]))
            later = _contract_datetime(_path_get(payload, str(rule["later_path"])), str(rule["later_path"]))
            if earlier > later or (rule.get("strict") and earlier == later):
                raise ValueError(f"{name}: fence time window is expired or unbounded")
        elif kind == "integer_order":
            left = _path_get(payload, str(rule["left_path"]))
