def _py_schema_annotation(schema: dict[str, Any]) -> str:
    """Render a recursive strict Pydantic annotation for the supported schema subset."""

    if "$ref" in schema:
        return str(schema["$ref"].rsplit("/", 1)[-1])
    if "enum" in schema:
        return "Literal[" + ", ".join(
            json.dumps(value, ensure_ascii=False) for value in schema["enum"]
        ) + "]"
    json_type = schema.get("type")
    if json_type == "string":
        if schema.get("format") == "date-time":
            return "Annotated[datetime, AwareDatetime()]"
        kwargs: list[str] = ["strict=True"]
        if schema.get("minLength") is not None:
            kwargs.append(f"min_length={schema['minLength']}")
        if schema.get("maxLength") is not None:
            kwargs.append(f"max_length={schema['maxLength']}")
        if schema.get("pattern") is not None:
            kwargs.append(f"pattern={json.dumps(schema['pattern'])}")
        return f"Annotated[str, Field({', '.join(kwargs)})]"
    if json_type == "integer":
        kwargs = ["strict=True"]
        if schema.get("minimum") is not None:
            kwargs.append(f"ge={schema['minimum']}")
        if schema.get("maximum") is not None:
            kwargs.append(f"le={schema['maximum']}")
        return f"Annotated[int, Field({', '.join(kwargs)})]"
    if json_type == "number":
        kwargs = ["strict=True", "allow_inf_nan=False"]
        if schema.get("minimum") is not None:
            kwargs.append(f"ge={schema['minimum']}")
        if schema.get("maximum") is not None:
            kwargs.append(f"le={schema['maximum']}")
        return f"Annotated[float, Field({', '.join(kwargs)})]"
    if json_type == "boolean":
        return "Annotated[bool, Field(strict=True)]"
    if json_type == "array":
        item = _py_schema_annotation(cast(dict[str, Any], schema["items"]))
        base = f"tuple[{item}, ...]"
        kwargs = []
        if schema.get("minItems") is not None:
            kwargs.append(f"min_length={schema['minItems']}")
        if schema.get("maxItems") is not None:
            kwargs.append(f"max_length={schema['maxItems']}")
        return f"Annotated[{base}, Field({', '.join(kwargs)})]" if kwargs else base
    if json_type == "object":
        additional = schema.get("additionalProperties")
        value_type = (
            _py_schema_annotation(cast(dict[str, Any], additional))
            if isinstance(additional, dict)
            else "object"
        )
        base = f"dict[str, {value_type}]"
        if schema.get("maxProperties") is not None:
            return f"Annotated[{base}, Field(max_length={schema['maxProperties']})]"
        return base
    return "object"


def _py_annotation(field: FieldSpec) -> str:
    base = _py_schema_annotation(field.value_schema)
    return f"{base} | None" if field.nullable else base


def _python_field_line(field: FieldSpec) -> str:
    ann = _py_annotation(field)
    return f"{field.name}: {ann}" if field.required else f"{field.name}: {ann} = None"


def _python_invariant_lines(name: str, schema: dict[str, Any]) -> list[str]:
    rules = _normalized_invariants(schema)
    if not rules:
        return []
    return [
        "",
        "    @model_validator(mode=\"after\")",
        "    def _contract_invariants(self) -> Self:",
        f"        _validate_contract_invariants({name!r}, self.model_dump(mode=\"json\"), OBJECT_INVARIANTS[{name!r}])",
        "        return self",
    ]

    # Kept below as an intentionally unreachable historical emitter until all
    # downstream consumers have migrated to the shared invariant DSL.
    has_rules = any(
        key in schema
        for key in (
            "x-memoria-paired-arrays",
            "x-memoria-value-pairs",
            "x-memoria-non-null-if",
            "x-memoria-distinct-fields",
            "x-memoria-approval-subjects",
            "x-memoria-confirmation-coverage",
            "x-memoria-epoch-semantics",
            "x-memoria-forbidden-values",
            "x-memoria-unique-by",
        )
    )
    if not has_rules:
        return []
    lines = ["", "    @model_validator(mode=\"after\")", "    def _contract_invariants(self) -> Self:"]
    for left, right in schema.get("x-memoria-paired-arrays", []):
        lines.append(f"        if len(self.{left}) != len(self.{right}):")
        lines.append(f'            raise ValueError("{left}/{right}: aligned arrays must have equal length")')
    for rule in schema.get("x-memoria-value-pairs", []):
        left = rule["left_field"]
        right = rule["right_field"]
        pairs = rule["pairs"]
        lines.append(f"        _pairs_{left}_{right} = {pairs!r}")
        lines.append(f"        if str(self.{left}) in _pairs_{left}_{right} and str(self.{right}) != _pairs_{left}_{right}[str(self.{left})]:")
        lines.append(f'            raise ValueError("{left}/{right}: restricted authority pair mismatch")')
        if rule["bidirectional"]:
            lines.append(f"        _inverse_{left}_{right} = {{value: key for key, value in _pairs_{left}_{right}.items()}}")
            lines.append(f"        if str(self.{right}) in _inverse_{left}_{right} and str(self.{left}) != _inverse_{left}_{right}[str(self.{right})]:")
            lines.append(f'            raise ValueError("{left}/{right}: restricted authority pair mismatch")')
    for rule in schema.get("x-memoria-non-null-if", []):
        trigger = rule["field"]
        equals = repr(rule["equals"])
        for target in rule["non_null_fields"]:
            lines.append(f"        if self.{trigger} == {equals} and self.{target} is None:")
            lines.append(f'            raise ValueError("{target}: required by {trigger}")')
    for left, right in schema.get("x-memoria-distinct-fields", []):
        lines.append(f"        if self.{left} == self.{right}:")
        lines.append(f'            raise ValueError("{left}/{right}: values must be distinct")')
    approval = schema.get("x-memoria-approval-subjects")
    if isinstance(approval, dict):
        proposer = approval["proposer_field"]
        co_subjects = approval["co_subjects_field"]
        required = approval["required_field"]
        lines.append(f"        _expected_approvals = {{self.{proposer}, *self.{co_subjects}}}")
        lines.append(f"        if set(self.{required}) != _expected_approvals or len(self.{required}) != len(_expected_approvals):")
        lines.append(f'            raise ValueError("{required}: must equal proposer plus co-subjects")')
    coverage = schema.get("x-memoria-confirmation-coverage")
    if isinstance(coverage, dict):
        required = coverage["required_subject_ids_field"]
        evidence = coverage["evidence_field"]
        subject = coverage["evidence_subject_field"]
        decision = coverage["evidence_decision_field"]
        accepted = repr(coverage["accepted_decision"])
        lines.append(f"        _evidence_subjects = [item.{subject} for item in self.{evidence}]")
        lines.append(f"        if any(str(item.{decision}) != {accepted} for item in self.{evidence}):")
        lines.append(f'            raise ValueError("{evidence}: every approval must carry the accepted decision")')
        lines.append(f"        if set(_evidence_subjects) != set(self.{required}) or len(_evidence_subjects) != len(set(_evidence_subjects)):")
        lines.append(f'            raise ValueError("{evidence}: must cover every required subject exactly once")')
        receipt_field = coverage.get("evidence_receipt_field")
        if isinstance(receipt_field, str):
            lines.append(f"        _approval_receipts = [item.{receipt_field} for item in self.{evidence}]")
            if coverage.get("require_unique_evidence_receipts"):
                lines.append("        if len(_approval_receipts) != len(set(_approval_receipts)):")
                lines.append(f'            raise ValueError("{evidence}: approval receipts must be unique")')
            for target in coverage.get("evidence_receipts_distinct_from_fields", []):
                lines.append(f"        if self.{target} in _approval_receipts:")
                lines.append(f'            raise ValueError("{evidence}: approval receipt cannot reuse {target}")')
    epoch = schema.get("x-memoria-epoch-semantics")
    if isinstance(epoch, dict):
        epoch_field = epoch["epoch_field"]
        allowed = tuple(epoch["zero_event_values"])
        lines.append(f"        if self.{epoch_field} == 0:")
        lines.append(f"            if str(self.event_type) not in {allowed!r}:")
        lines.append('                raise ValueError("event_type: epoch 0 is lifecycle-only")')
        for target in epoch["zero_null_fields"]:
            lines.append(f"            if self.{target} is not None:")
            lines.append(f'                raise ValueError("{target}: epoch 0 requires null")')
        lines.append("        else:")
        for target in epoch["positive_non_null_fields"]:
            lines.append(f"            if self.{target} is None:")
            lines.append(f'                raise ValueError("{target}: issued events require a complete fence")')
    for rule in schema.get("x-memoria-forbidden-values", []):
        target = rule["field"]
        values = tuple(rule["values"])
        lines.append(f"        if str(self.{target}) in {values!r}:")
        lines.append(f'            raise ValueError("{target}: forbidden fail-closed value")')
    for rule in schema.get("x-memoria-unique-by", []):
        target = rule["field"]
        item_field = rule["item_field"]
        lines.append(f"        _keys_{target} = [item.{item_field} for item in self.{target}]")
        lines.append(f"        if len(_keys_{target}) != len(set(_keys_{target})):")
        lines.append(f'            raise ValueError("{target}: {item_field} must be unique")')
    lines.append("        return self")
    return lines


