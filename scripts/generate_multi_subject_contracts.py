"""Deterministic code generator for the Memoria multi-subject canonical contracts.

Single source of truth:
    packages/contracts/schemas/multi-subject/multi-subject.schema.json

The schema holds two independent contract families (ADR-0033 / PR-01):

- the canonical enums in ``$defs`` (frozen by ADR-0033 and later contract versions);
- the object contracts in ``objects`` (PR-01 / section 9.6): BindingManifest,
  RuntimeProfile + runtime-profile-v1 signed envelope, PolicyDecision /
  PolicyReceipt, SubjectResolution, MemoryEvent / MemoryWriteFence,
  NotificationIntent with NotificationFence / RelationshipSnapshot /
  RecipientSnapshot, SessionEvent / SessionEpochFence.

Outputs:
    python/multi_subject_contracts.py        (enums + Pydantic v2 models)
    typescript/multi_subject_contracts.ts    (enums + types + guards + validators)
    go/multi_subject_contracts.go            (enums + structs + Validate seam)
    firmware/multi_subject_contracts.compact.json
    apps/miniprogram/generated/multi-subject-contracts.js
                                                (CommonJS enums + lifecycle guards)

The generator is deterministic: it emits no timestamps, embeds the canonical
schema sha256 as ``source_hash``, iterates the schema in document order, and
fails on structural drift. Use ``--check`` in CI to prove regeneration produces
no diff.
"""

