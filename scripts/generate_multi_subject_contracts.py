def _screaming(name: str) -> str:
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name).upper()


def _pascal(value: str) -> str:
    """Convert a snake_case value to PascalCase, preserving an underscore before digit parts."""
    parts = value.split("_")
    out: list[str] = []
    for i, part in enumerate(parts):
        if not part:
            continue
        if part[0].isdigit():
            out.append(part)
        else:
            out.append(part[0].upper() + part[1:])
        if i + 1 < len(parts) and parts[i + 1] and parts[i + 1][0].isdigit():
            out.append("_")
    return "".join(out)


def _ts_go_key(name: str, value: str) -> str:
    key = _pascal(value)
    if key[0].isdigit():
        return f"{name}{key}"
    return key


def _commonjs_key(name: str, value: str) -> str:
    """Return the stable Mini Program property spelling used by existing consumers."""
    parts = [part for part in value.split("_") if part]
    key = "".join(part[:1].upper() + part[1:].lower() for part in parts)
    if key and key[0].isdigit():
        # Preserve the pre-codegen Mini Program spelling for AgeBand's ``14_17``.
        return f"Age{value}"
    if not key:
        _fail(f"{name}: cannot derive CommonJS key from {value!r}")
    return key


def _go_field_name(name: str) -> str:
    out = "".join(part[:1].upper() + part[1:] for part in name.split("_") if part)
    out = re.sub(r"Ids\b", "IDs", out)
    return re.sub(r"Id\b", "ID", out)


def _one_line(value: str) -> str:
    return " ".join(value.split())


