def _fail(message: str) -> NoReturn:
    raise ValueError(f"multi-subject contract drift: {message}")


def load_schema(path: Path) -> dict[str, Any]:
    """Load and structurally validate the canonical schema."""
    data = json.loads(path.read_text(encoding="utf-8"))
    if data.get("$id") != SCHEMA_ID:
        _fail(f"unexpected $id {data.get('$id')!r}")
    version = data.get("properties", {}).get("schema_version", {}).get("const")
    if not isinstance(version, int) or version < 1:
        _fail("schema_version must be a positive integer const")
    defs = data.get("$defs")
    if not isinstance(defs, dict):
        _fail("missing $defs")
    if tuple(defs.keys()) != REQUIRED_ENUMS:
        _fail(f"enum set/order drift: {tuple(defs.keys())} != {REQUIRED_ENUMS}")
    index = data.get("properties", {})
    for name in REQUIRED_ENUMS:
        if index.get(name, {}).get("$ref") != f"#/$defs/{name}":
            _fail(f"index property {name} must $ref #/$defs/{name}")
    for name, schema in defs.items():
        _validate_enum(name, schema)
    _validate_objects(data)
    return cast(dict[str, Any], data)


def _validate_enum(name: str, schema: dict[str, Any]) -> None:
    if schema.get("title") != name:
        _fail(f"{name}: title mismatch")
    if schema.get("type") != "string":
        _fail(f"{name}: type must be string")
    values = schema.get("enum")
    if not isinstance(values, list) or not values:
        _fail(f"{name}: enum must be a non-empty list")
    if len(set(values)) != len(values):
        _fail(f"{name}: duplicate enum values")
    if any(not isinstance(v, str) or not v for v in values):
        _fail(f"{name}: enum values must be non-empty strings")
    meta = schema.get("x-memoria")
    if not isinstance(meta, dict):
        _fail(f"{name}: missing x-memoria metadata")
    for key in ("contract_version", "frozen_by", "source", "missing_value_policy"):
        if key not in meta:
            _fail(f"{name}: x-memoria missing {key}")
    policy = meta["missing_value_policy"]
    if policy not in ALLOWED_MISSING_VALUE_POLICIES:
        _fail(f"{name}: unknown missing_value_policy {policy!r}")
    default = meta.get("default")
    if default is not None and default not in values:
        _fail(f"{name}: default {default!r} not in enum")
    notes = meta.get("value_notes")
    if not isinstance(notes, dict) or set(notes) != set(values):
        _fail(f"{name}: value_notes must cover exactly the enum values")
    for note in notes.values():
        if not isinstance(note, str) or not note or "\n" in note:
            _fail(f"{name}: value notes must be single-line non-empty strings")


def _validate_object_enum(name: str, schema: dict[str, Any]) -> None:
    if schema.get("type") != "string":
        _fail(f"objects.{name}: type must be string")
    values = schema.get("enum")
    if not isinstance(values, list) or not values:
        _fail(f"objects.{name}: enum must be a non-empty list")
    if len(set(values)) != len(values):
        _fail(f"objects.{name}: duplicate enum values")
    if any(not isinstance(v, str) or not v for v in values):
        _fail(f"objects.{name}: enum values must be non-empty strings")


def _resolve_ref(ref: str, object_defs: dict[str, Any], canonical: set[str]) -> tuple[str, str]:
    if ref.startswith(CANONICAL_REF_PREFIX):
        name = ref[len(CANONICAL_REF_PREFIX) :]
        if name not in canonical:
            _fail(f"unresolvable canonical $ref {ref}")
        return "canonical", name
    if ref.startswith(OBJECT_REF_PREFIX):
        name = ref[len(OBJECT_REF_PREFIX) :]
        if name not in object_defs:
            _fail(f"unresolvable object $ref {ref}")
        return "object", name
    _fail(f"unsupported $ref {ref}")


def _validate_field_schema(where: str, schema: dict[str, Any], object_defs: dict[str, Any], canonical: set[str]) -> None:
    if not isinstance(schema, dict):
        _fail(f"{where}: schema must be an object")
    if "$ref" in schema:
        _resolve_ref(schema["$ref"], object_defs, canonical)
        return
    if "enum" in schema:
        _fail(f"{where}: inline enum is forbidden; reference one canonical $defs enum")
    if "anyOf" in schema:
        branches = schema["anyOf"]
        if not isinstance(branches, list) or len(branches) != 2:
            _fail(f"{where}: anyOf must have exactly two branches (value + null)")
        for branch in branches:
            _validate_field_schema(f"{where}.anyOf", branch, object_defs, canonical)
        return
    json_type = schema.get("type")
    if isinstance(json_type, list):
        if json_type.count("null") != 1 or len(json_type) != 2:
            _fail(f"{where}: type list must be exactly [<type>, \"null\"]")
        json_type = json_type[0] if json_type[0] != "null" else json_type[1]
    if json_type == "null":
        return
    if json_type == "string":
        for key in ("minLength", "maxLength"):
            if key in schema and (not isinstance(schema[key], int) or schema[key] <= 0):
                _fail(f"{where}: {key} must be a positive integer")
        if "pattern" in schema and not isinstance(schema["pattern"], str):
            _fail(f"{where}: pattern must be a string")
        if "format" in schema and schema["format"] != "date-time":
            _fail(f"{where}: format must be date-time")
        if "const" in schema and not isinstance(schema["const"], str):
            _fail(f"{where}: string const must be a string")
    elif json_type in ("integer", "number"):
        for key in ("minimum", "maximum"):
            if key in schema and not isinstance(schema[key], (int, float)):
                _fail(f"{where}: {key} must be numeric")
        if "const" in schema and not isinstance(schema["const"], (int, float)):
            _fail(f"{where}: numeric const must be numeric")
    elif json_type == "boolean":
        if "const" in schema and not isinstance(schema["const"], bool):
            _fail(f"{where}: boolean const must be boolean")
    elif json_type == "array":
        items = schema.get("items")
        if not isinstance(items, dict):
            _fail(f"{where}: array items must be a schema")
        _validate_field_schema(f"{where}.items", items, object_defs, canonical)
        for key in ("minItems", "maxItems"):
            if key in schema and (not isinstance(schema[key], int) or schema[key] < 0):
                _fail(f"{where}: {key} must be a non-negative integer")
        if schema.get("minItems", 0) > schema.get("maxItems", sys.maxsize):
            _fail(f"{where}: minItems must not exceed maxItems")
    elif json_type == "object":
        if "maxProperties" in schema and (not isinstance(schema["maxProperties"], int) or schema["maxProperties"] <= 0):
            _fail(f"{where}: maxProperties must be a positive integer")
        addl = schema.get("additionalProperties")
        if isinstance(addl, dict):
            _validate_field_schema(f"{where}.additionalProperties", addl, object_defs, canonical)
        elif addl is not True:
            _fail(f"{where}: free-form object must set additionalProperties to a schema or true")
    else:
        _fail(f"{where}: unsupported type {json_type!r}")


def _validate_object_def(
    name: str,
    schema: dict[str, Any],
    object_defs: dict[str, Any],
    canonical: set[str],
) -> None:
    if schema.get("title") != name:
        _fail(f"objects.{name}: title mismatch")
    if not isinstance(schema.get("description"), str) or not schema["description"]:
        _fail(f"objects.{name}: missing description")
    if "enum" in schema:
        _fail(f"objects.{name}: object-local enum is forbidden; move it to canonical $defs")
    if "x-memoria-extends" in schema:
        base_name = schema["x-memoria-extends"]
        if not isinstance(base_name, str) or base_name not in object_defs:
            _fail(f"objects.{name}: x-memoria-extends must reference an existing definition")
        if base_name == name:
            _fail(f"objects.{name}: cannot extend itself")
        if schema.get("unevaluatedProperties") is not False:
            _fail(f"objects.{name}: extend contract must set unevaluatedProperties false")
        if schema.get("type") != "object":
            _fail(f"objects.{name}: extend contract type must be object")
        properties = schema.get("properties")
        if not isinstance(properties, dict) or not properties:
            _fail(f"objects.{name}: extend contract needs its own properties")
        required = schema.get("required")
        if not isinstance(required, list) or not required or any(p not in properties for p in required):
            _fail(f"objects.{name}: extend required must be a non-empty subset of properties")
        for pname, pschema in properties.items():
            _validate_field_schema(f"objects.{name}.{pname}", pschema, object_defs, canonical)
        _validate_object_invariants(name, schema, properties)
        return
    if schema.get("type") != "object":
        _fail(f"objects.{name}: type must be object")
    if schema.get("additionalProperties") is not False and schema.get("unevaluatedProperties") is not False:
        _fail(f"objects.{name}: additionalProperties/unevaluatedProperties must be false")
    properties = schema.get("properties")
    if not isinstance(properties, dict) or not properties:
        _fail(f"objects.{name}: missing properties")
    required = schema.get("required")
    if not isinstance(required, list) or not required or any(p not in properties for p in required):
        _fail(f"objects.{name}: required must be a non-empty subset of properties")
    for pname, pschema in properties.items():
        _validate_field_schema(f"objects.{name}.{pname}", pschema, object_defs, canonical)
    _validate_object_invariants(name, schema, properties)


def _validate_object_invariants(
    name: str, schema: dict[str, Any], properties: dict[str, Any]
) -> None:
    """Validate the declarative cross-field subset emitted in every language."""

    def field(value: object, where: str) -> str:
        if not isinstance(value, str) or value not in properties:
            _fail(f"objects.{name}.{where}: unknown field {value!r}")
        return value

    def path(value: object, where: str) -> str:
        if not isinstance(value, str) or not value:
            _fail(f"objects.{name}.{where}: path must be a non-empty string")
        root = value.split(".", 1)[0]
        if root not in properties:
            _fail(f"objects.{name}.{where}: unknown root field {root!r}")
        return value

    def when(rule: object, where: str) -> None:
        if not isinstance(rule, dict):
            _fail(f"objects.{name}.{where}: when must be an object")
        path(rule.get("path"), f"{where}.path")
        operators = {"equals", "not_equals", "in", "not_in"} & set(rule)
        if len(operators) != 1:
            _fail(f"objects.{name}.{where}: when needs exactly one operator")
        for operator in ("in", "not_in"):
            if operator in rule and (not isinstance(rule[operator], list) or not rule[operator]):
                _fail(f"objects.{name}.{where}.{operator}: expected non-empty list")

    for index, pair in enumerate(schema.get("x-memoria-paired-arrays", [])):
        if not isinstance(pair, list) or len(pair) != 2:
            _fail(f"objects.{name}.x-memoria-paired-arrays[{index}] must contain two fields")
        field(pair[0], "x-memoria-paired-arrays")
        field(pair[1], "x-memoria-paired-arrays")
    for index, rule in enumerate(schema.get("x-memoria-value-pairs", [])):
        if not isinstance(rule, dict):
            _fail(f"objects.{name}.x-memoria-value-pairs[{index}] must be an object")
        field(rule.get("left_field"), "x-memoria-value-pairs.left_field")
        field(rule.get("right_field"), "x-memoria-value-pairs.right_field")
        pairs = rule.get("pairs")
        if not isinstance(pairs, dict) or not pairs or any(
            not isinstance(key, str) or not isinstance(value, str)
            for key, value in pairs.items()
        ):
            _fail(f"objects.{name}.x-memoria-value-pairs[{index}].pairs invalid")
        if not isinstance(rule.get("bidirectional"), bool):
            _fail(f"objects.{name}.x-memoria-value-pairs[{index}].bidirectional must be bool")
    for index, rule in enumerate(schema.get("x-memoria-non-null-if", [])):
        if not isinstance(rule, dict):
            _fail(f"objects.{name}.x-memoria-non-null-if[{index}] must be an object")
        field(rule.get("field"), "x-memoria-non-null-if.field")
        values = rule.get("non_null_fields")
        if not isinstance(values, list) or not values:
            _fail(f"objects.{name}.x-memoria-non-null-if[{index}] needs fields")
        for value in values:
            field(value, "x-memoria-non-null-if.non_null_fields")
    for index, pair in enumerate(schema.get("x-memoria-distinct-fields", [])):
        if not isinstance(pair, list) or len(pair) != 2:
            _fail(f"objects.{name}.x-memoria-distinct-fields[{index}] must contain two fields")
        field(pair[0], "x-memoria-distinct-fields")
        field(pair[1], "x-memoria-distinct-fields")
    approval = schema.get("x-memoria-approval-subjects")
    if approval is not None:
        if not isinstance(approval, dict):
            _fail(f"objects.{name}.x-memoria-approval-subjects must be an object")
        for key in ("proposer_field", "co_subjects_field", "required_field"):
            field(approval.get(key), f"x-memoria-approval-subjects.{key}")
    coverage = schema.get("x-memoria-confirmation-coverage")
    if coverage is not None:
        if not isinstance(coverage, dict):
            _fail(f"objects.{name}.x-memoria-confirmation-coverage must be an object")
        for key in ("required_subject_ids_field", "evidence_field"):
            field(coverage.get(key), f"x-memoria-confirmation-coverage.{key}")
    epoch = schema.get("x-memoria-epoch-semantics")
    if epoch is not None:
        if not isinstance(epoch, dict):
            _fail(f"objects.{name}.x-memoria-epoch-semantics must be an object")
        field(epoch.get("epoch_field"), "x-memoria-epoch-semantics.epoch_field")
        for key in ("zero_null_fields", "positive_non_null_fields"):
            values = epoch.get(key)
            if not isinstance(values, list):
                _fail(f"objects.{name}.x-memoria-epoch-semantics.{key} must be a list")
            for value in values:
                field(value, f"x-memoria-epoch-semantics.{key}")
    for key in ("x-memoria-forbidden-values", "x-memoria-unique-by"):
        rules = schema.get(key, [])
        if not isinstance(rules, list):
            _fail(f"objects.{name}.{key} must be a list")
        for rule in rules:
            if not isinstance(rule, dict):
                _fail(f"objects.{name}.{key} entries must be objects")
            field(rule.get("field"), f"{key}.field")
    for index, rule in enumerate(schema.get("x-memoria-conditional-fields", [])):
        if not isinstance(rule, dict):
            _fail(f"objects.{name}.x-memoria-conditional-fields[{index}] must be an object")
        when(rule.get("when"), f"x-memoria-conditional-fields[{index}].when")
        for key in ("require_non_null", "require_null", "require_non_empty", "require_empty"):
            values = rule.get(key, [])
            if not isinstance(values, list):
                _fail(f"objects.{name}.x-memoria-conditional-fields[{index}].{key} must be a list")
            for value in values:
                path(value, f"x-memoria-conditional-fields[{index}].{key}")
        for key in ("require_equals", "require_in", "forbid_contains"):
            values = rule.get(key, {})
            if not isinstance(values, dict):
                _fail(f"objects.{name}.x-memoria-conditional-fields[{index}].{key} must be an object")
            for value in values:
                path(value, f"x-memoria-conditional-fields[{index}].{key}")
    for key in ("x-memoria-equal-paths", "x-memoria-set-equal-paths"):
        entries = schema.get(key, [])
        if not isinstance(entries, list):
            _fail(f"objects.{name}.{key} must be a list")
        for index, entry in enumerate(entries):
            paths = entry if isinstance(entry, list) else entry.get("paths") if isinstance(entry, dict) else None
            if not isinstance(paths, list) or len(paths) < 2:
                _fail(f"objects.{name}.{key}[{index}] needs at least two paths")
            for value in paths:
                path(value, f"{key}[{index}]")
            if isinstance(entry, dict) and "when" in entry:
                when(entry["when"], f"{key}[{index}].when")
    for index, rule in enumerate(schema.get("x-memoria-record-set-equals", [])):
        if not isinstance(rule, dict):
            _fail(f"objects.{name}.x-memoria-record-set-equals[{index}] must be an object")
        path(rule.get("left_path"), f"x-memoria-record-set-equals[{index}].left_path")
        path(rule.get("right_path"), f"x-memoria-record-set-equals[{index}].right_path")
        left_fields = rule.get("left_fields")
        right_fields = rule.get("right_fields")
        if not isinstance(left_fields, list) or not isinstance(right_fields, list) or len(left_fields) != len(right_fields) or not left_fields:
            _fail(f"objects.{name}.x-memoria-record-set-equals[{index}] field mappings invalid")
    for index, rule in enumerate(schema.get("x-memoria-record-coverage", [])):
        if not isinstance(rule, dict):
            _fail(f"objects.{name}.x-memoria-record-coverage[{index}] must be an object")
        path(rule.get("required_ids_path"), f"x-memoria-record-coverage[{index}].required_ids_path")
        path(rule.get("records_path"), f"x-memoria-record-coverage[{index}].records_path")
        if not isinstance(rule.get("record_id_field"), str):
            _fail(f"objects.{name}.x-memoria-record-coverage[{index}].record_id_field invalid")
        if "when" in rule:
            when(rule["when"], f"x-memoria-record-coverage[{index}].when")
    for index, rule in enumerate(schema.get("x-memoria-time-order", [])):
        if not isinstance(rule, dict) or not isinstance(rule.get("strict"), bool):
            _fail(f"objects.{name}.x-memoria-time-order[{index}] invalid")
        path(rule.get("earlier_path"), f"x-memoria-time-order[{index}].earlier_path")
        path(rule.get("later_path"), f"x-memoria-time-order[{index}].later_path")
        if "when" in rule:
            when(rule["when"], f"x-memoria-time-order[{index}].when")
    for index, rule in enumerate(schema.get("x-memoria-integer-order", [])):
        if not isinstance(rule, dict) or rule.get("operator") not in (">=", ">", "=="):
            _fail(f"objects.{name}.x-memoria-integer-order[{index}] invalid")
        path(rule.get("left_path"), f"x-memoria-integer-order[{index}].left_path")
        path(rule.get("right_path"), f"x-memoria-integer-order[{index}].right_path")
    for index, rule in enumerate(schema.get("x-memoria-selected-record-integer-order", [])):
        if not isinstance(rule, dict) or rule.get("operator") not in (">=", "<=", ">", "<", "=="):
            _fail(f"objects.{name}.x-memoria-selected-record-integer-order[{index}] invalid")
        for key in ("selector_path", "records_path", "other_path"):
            path(rule.get(key), f"x-memoria-selected-record-integer-order[{index}].{key}")
        for key in ("record_selector_field", "record_value_field"):
            if not isinstance(rule.get(key), str) or not rule[key]:
                _fail(f"objects.{name}.x-memoria-selected-record-integer-order[{index}].{key} invalid")
    for index, rule in enumerate(schema.get("x-memoria-requires-capability", [])):
        if not isinstance(rule, dict) or not isinstance(rule.get("state_values"), list) or not isinstance(rule.get("capability"), str):
            _fail(f"objects.{name}.x-memoria-requires-capability[{index}] invalid")
        path(rule.get("state_path"), f"x-memoria-requires-capability[{index}].state_path")
